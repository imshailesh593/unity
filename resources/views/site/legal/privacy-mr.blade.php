<p>युनिटी ("युनिटी", "आम्ही", "आमचे") हे मॅव्हरिक इन्फोटेक द्वारे संचालित आहे. हे गोपनीयता धोरण स्पष्ट करते की तुम्ही युनिटी अ‍ॅप आणि वेबसाइट वापरता तेव्हा आम्ही कोणती वैयक्तिक माहिती गोळा करतो, ती का गोळा करतो आणि त्यावर तुमचे कोणते अधिकार आहेत.</p>

