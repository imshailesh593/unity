<p>This policy explains when a refund of the Unity activation fee may apply.</p>

<h2>1. Activation fee</h2>
<p>The activation fee is a one-time payment, not a subscription, and is generally non-refundable once your account has been successfully activated.</p>

<h2>2. When a refund may apply</h2>
<ul>
    <li>You were charged more than once for the same activation (duplicate payment).</li>
    <li>Payment was deducted from your account but never confirmed by Unity, and your account was not activated as a result.</li>
    <li>A verified technical error on our end prevented activation despite a successful payment.</li>
</ul>

<h2>3. How to request a refund</h2>
<p>Contact <a href="mailto:support@unityapp.in">support@unityapp.in</a> with your registered phone number and payment reference within 7 days of the transaction. We will investigate and respond within 5 business days.</p>

<h2>4. Refund timeline</h2>
<p>Approved refunds are processed back to the original payment method via Razorpay and typically reflect within 5–10 business days, depending on your bank or payment provider.</p>

<h2>5. Contact</h2>
<p>For any refund-related question, contact <a href="mailto:support@unityapp.in">support@unityapp.in</a>.</p>

