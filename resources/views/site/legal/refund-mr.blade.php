<p>युनिटी सक्रियता फीचा परतावा कधी लागू होऊ शकतो हे हे धोरण स्पष्ट करते.</p>

<h2>१. सक्रियता फी</h2>
<p>सक्रियता फी ही एकवेळची पेमेंट आहे, सबस्क्रिप्शन नाही, आणि तुमचे खाते यशस्वीरित्या सक्रिय झाल्यानंतर ती सर्वसाधारणपणे परत करण्यायोग्य नसते.</p>

<h2>२. परतावा कधी लागू होऊ शकतो</h2>
<ul>
    <li>एकाच सक्रियतेसाठी तुमच्याकडून एकापेक्षा जास्त वेळा शुल्क आकारले गेले (डुप्लिकेट पेमेंट).</li>
