<p>या अटी व शर्ती ("अटी") मॅव्हरिक इन्फोटेक द्वारे संचालित युनिटी अ‍ॅप आणि वेबसाइटच्या वापरावर लागू होतात ("युनिटी", "आम्ही"). खात्याची नोंदणी करून तुम्ही या अटींना संमती देता.</p>

<h2>१. पात्रता</h2>
<p>युनिटी वापरण्यासाठी तुमचे वय किमान १८ वर्षे असणे आणि कायदेशीर बंधनकारक करार करण्यास सक्षम असणे आवश्यक आहे. युनिटी सध्या पंढरपूर आणि सोलापूर जिल्ह्यांवर केंद्रित आहे, इतर प्रदेश लवकरच जोडले जातील.</p>

<h2>२. खाते नोंदणी आणि पडताळणी</h2>
<p>नोंदणीसाठी वैध मोबाईल नंबर आवश्यक आहे, जो एकवेळ पासवर्ड (OTP) द्वारे पडताळला जातो. तुमची खाते ओळखपत्रे सुरक्षित ठेवण्याची आणि तुमच्या खात्याअंतर्गत सर्व क्रियाकलापांची जबाबदारी तुमची आहे.</p>

<h2>३. खाते सक्रियता</h2>
<p>तुम्ही पेमेंटच्या वेळी दर्शवलेली एकवेळची सक्रियता फी भरेपर्यंत तुमचे खाते मर्यादित "प्रलंबित" स्थितीत राहते. सक्रियतेची स्थिती केवळ आमच्या प्रणालींद्वारे ठरवली जाते आणि ती हाताने दावा करता येत नाही.</p>

<h2>४. पुनरावलोकन आणि नियमन</h2>
<p>सामुदायिक पोस्ट्स आणि ब्लॉग पोस्ट्स प्रकाशित होण्यापूर्वी आमच्या प्रशासकीय टीमकडून तपासल्या जातात. आमच्या सामुदायिक मानकांना अनुसरून नसलेला कोणताही मजकूर आम्ही नाकारू किंवा काढून टाकू शकतो.</p>

