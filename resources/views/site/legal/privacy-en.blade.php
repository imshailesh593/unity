<p>Unity ("Unity", "we", "us", "our") is operated by Maveric Infotech. This Privacy Policy explains what personal information we collect when you use the Unity app and website, why we collect it, and what rights you have over it.</p>

<h2>1. Information we collect</h2>
<ul>
    <li><strong>Account information</strong> — your name, phone number, and (optionally) email address.</li>
    <li><strong>Identity verification</strong> — a Firebase-issued identifier confirming your phone number was verified by OTP.</li>
    <li><strong>Payment records</strong> — the amount, status, and transaction reference for your activation fee payment (processed by Razorpay; we do not receive or store your card, UPI, or bank details).</li>
    <li><strong>Device token</strong> — a Firebase Cloud Messaging identifier, so we can deliver push notifications to your device.</li>
    <li><strong>Content you submit</strong> — anything you post through an approved author account (business listings, updates).</li>
</ul>

<h2>2. How we use your information</h2>
<ul>
    <li>To verify your identity and activate your account.</li>
    <li>To track your account's activation status.</li>
    <li>To process your activation fee payment and issue a receipt.</li>
    <li>To send you transactional notifications — OTPs, activation confirmations, payment receipts, and relevant community updates.</li>
    <li>To keep the platform safe — detecting fraud, fake accounts, and abuse.</li>
</ul>

<h2>3. Third-party service providers</h2>
<p>We share the minimum data necessary with the following providers to operate Unity:</p>
<ul>
    <li><strong>Firebase / Google</strong> — phone OTP verification and push notifications.</li>
    <li><strong>Razorpay</strong> — payment processing for the activation fee.</li>
    <li><strong>MSG91</strong> — transactional SMS delivery (OTP fallback, confirmations).</li>
    <li><strong>Hostinger</strong> — application hosting and database storage.</li>
</ul>
<p>We do not sell your personal information to advertisers or any third party, and Unity does not run third-party advertising.</p>

<h2>4. Data sharing &amp; disclosure</h2>
<p>Beyond the service providers listed above, we disclose personal information only where required by law, to enforce our Terms &amp; Conditions, or to protect the rights, safety, and security of Unity or its users.</p>

<h2>5. Data security</h2>
<p>Passwords are stored using industry-standard one-way hashing. Payment webhooks are signature-verified. Access to the admin panel is role-restricted. No method of transmission or storage is 100% secure, but we take reasonable technical and organisational measures to protect your data.</p>

<h2>6. Your rights</h2>
<p>Under India's Digital Personal Data Protection Act, 2023, you have the right to:</p>
<ul>
    <li>Access the personal information we hold about you.</li>
    <li>Request correction of inaccurate information.</li>
    <li>Request deletion of your account and associated personal data, subject to any legal retention requirements (see our <a href="{{ route('legal.data') }}">Data Policy</a>).</li>
    <li>Withdraw consent for non-essential processing.</li>
</ul>
<p>To exercise any of these rights, contact us using the details in Section 9.</p>

<h2>7. Children's privacy</h2>
<p>Unity is intended for users aged 18 and above. We do not knowingly collect personal information from anyone under 18.</p>

